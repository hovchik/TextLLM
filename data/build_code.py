#!/usr/bin/env python3
"""Collect source code for the copilot model, from permissively licensed public code and your own projects.

Every source writes data/code/<source>/shard_XXXXX.txt (documents separated by <|endoftext|>, as for
the book corpus). Each document is one source file and starts with a header line in the file's own
comment syntax (`# path: project/app.py`), so the model knows the language and the file it is in.

  source        flag                       what it is                                   licence check
  ------------  -------------------------  -------------------------------------------  ----------------------------
  local/<name>  --local FOLDER (repeat)    projects on this PC (your own code)           yours: you decide
  github        --github-repos N           public GitHub repositories, most stars first  GitHub's licence field must be
                --github-repo owner/name   ...or exactly these repositories              a permissive licence (below)
  hf            --hf-gb G                  codeparrot/github-code-clean (Hugging Face)    per-file licence column

Permissive licences only (--licenses, default all of these): MIT, MIT-0, Apache-2.0, BSD-2-Clause,
BSD-3-Clause, 0BSD, ISC, Unlicense, CC0-1.0, Zlib, BSL-1.0. Copyleft (GPL, LGPL, AGPL, MPL, EPL),
"other", and repositories with no licence are never downloaded: code without a licence is all
rights reserved, even when it is public. Each GitHub repository's licence text, URL and commit go to
data/code/github/licenses/ and attribution.jsonl, and data/code/ATTRIBUTION.md lists them all.

Every file goes through the same filters:
  * folders: .git, node_modules, virtualenvs, build output, vendored code, caches (and, for local
    projects, everything your .gitignore files exclude);
  * secrets: .env files, private keys, keystores, cloud credential files are never read; tokens
    (GitHub, AWS, Google, Stripe, OpenAI, Hugging Face, Slack, JWT...) and `password = "..."`-style
    values are replaced with <REDACTED>; a file containing a private key is dropped;
  * junk: binary, minified, generated ("do not edit"), tiny or huge (--max-file-kb) files;
  * duplicates: the same file content is kept once (forks, copied libraries).

Usage:
  python data/build_code.py --local C:/Users/me/projects/app --local D:/work/tool
  python data/build_code.py --github-repos 200 --langs python,javascript,typescript --min-stars 100
  python data/build_code.py --github-repo pallets/flask --github-repo psf/requests
  python data/build_code.py --hf-gb 0.5 --langs python
Set GITHUB_TOKEN (any personal token, no scopes needed) for GitHub's higher rate limit.
Downloads resume: run the same command again and finished repositories are skipped.
"""
