# ---------------------------------------------------------------- one file
def clean_source(raw, path, max_kb):
    """(text, redactions) for a source file's bytes, or (None, reason) if it should be skipped."""
    if len(raw) > max_kb * 1024:
        return None, "too_big"
    if b"\0" in raw[:8192]:
        return None, "binary"
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None, "not_utf8"
    text = text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
    if path.lower().endswith(".ipynb"):
        text = notebook_code(text)
        if text is None:
            return None, "bad_notebook"
    lines = text.split("\n")
    if len(text.strip()) < 40 or len([l for l in lines if l.strip()]) < 3:
        return None, "too_short"
    longest = max(map(len, lines))
    if longest > 5000 or len(text) / max(1, len(lines)) > 200:  # minified bundles, embedded data
        return None, "minified"
    if GENERATED.search(text[:600]):
        return None, "generated"
    text, n = scrub(text)
    if text is None:
        return None, "private_key"
    return fim.defuse(text.rstrip() + "\n"), n


def notebook_code(text):
    """The code cells of a Jupyter notebook, separated by # %% markers (outputs are dropped)."""
    try:
        nb = json.loads(text)
    except ValueError:
        return None
    cells = []
    for c in nb.get("cells", []):
        if c.get("cell_type") == "code":
            src = "".join(c.get("source", [])) if isinstance(c.get("source"), list) else str(c.get("source", ""))
            if src.strip():
                cells.append(src.rstrip())
    return "\n\n# %%\n".join(cells) if cells else None


def make_doc(display_path, comment, text):
    return L.header(display_path, comment) + "\n" + text


def skip_dir(name):
    return name in SKIP_DIRS or (name.startswith(".") and name not in KEEP_HIDDEN) or name.endswith(".egg-info")


class Dedup:
    """Remembers a hash of every file's content (whitespace-insensitive) in <out>/hashes.list (not .txt: every .txt here is read as training text)."""

    def __init__(self, path):
        self.path, self.seen = path, set()
        if path and os.path.exists(path):
            self.seen = set(open(path).read().split())
        self.f = open(path, "a") if path else None

    def new(self, text):
        h = hashlib.sha1(" ".join(text.split()).encode()).hexdigest()[:20]
        if h in self.seen:
            return False
        self.seen.add(h)
        if self.f:
            self.f.write(h + "\n")
        return True

    def close(self):
        if self.f:
            self.f.close()


class Writer:
    """Shards plus files.jsonl (path, language, size, licence) for one source folder."""

    def __init__(self, outdir, idx=0, size=0, fresh=False):
        from data.build_corpus import ShardWriter

        if fresh and os.path.isdir(outdir):
            for f in os.listdir(outdir):
                if f.startswith("shard_") or f in ("files.jsonl", "hashes.list"):
                    os.remove(os.path.join(outdir, f))
        os.makedirs(outdir, exist_ok=True)
        self.outdir = outdir
        self.w = ShardWriter(outdir, idx, size)
        self.index = open(os.path.join(outdir, "files.jsonl"), "a", encoding="utf-8")

    def write(self, doc, **meta):
        self.w.write(doc)
        self.index.write(json.dumps({**meta, "chars": len(doc)}) + "\n")

    def checkpoint(self):
        self.index.flush()
        return self.w.checkpoint()

    def close(self):
        self.index.close()
        self.w.close()


# ---------------------------------------------------------------- local projects
def slug(folder):
    from core import paths

    name = paths.safe_name(os.path.basename(os.path.normpath(folder)), "project").strip("-")[:40]
    return f"{name or 'project'}-{hashlib.sha1(os.path.abspath(folder).encode()).hexdigest()[:6]}"


def scan_folder(root, langs, max_kb, stats):
    """Yield (relative path, language, comment, text) for the source files of one project folder,
    following its .gitignore files (and .git/info/exclude)."""
    rules = Ignore()
    rules.add_file(os.path.join(root, ".git", "info", "exclude"))
    for d, dirs, files in os.walk(root, topdown=True):
        rel_d = os.path.relpath(d, root).replace(os.sep, "/")
        rel_d = "" if rel_d == "." else rel_d
        if ".gitignore" in files:
            rules.add_file(os.path.join(d, ".gitignore"), base=rel_d)
        keep = []
        for x in sorted(dirs):
            rp = f"{rel_d}/{x}" if rel_d else x
            if skip_dir(x) or rules.ignored(rp, is_dir=True) or os.path.islink(os.path.join(d, x)):
                stats["skipped_dirs"] += 1
            else:
                keep.append(x)
        dirs[:] = keep
        for fn in sorted(files):
            rp = f"{rel_d}/{fn}" if rel_d else fn
            full = os.path.join(d, fn)
            if skip_file(fn):
                stats["skip:secret_file"] += 1
                continue
            if rules.ignored(rp) or os.path.islink(full):
                stats["skip:gitignore"] += 1
                continue
            try:
                with open(full, "rb") as f:
                    raw = f.read(max_kb * 1024 + 1)
            except OSError:
                stats["skip:unreadable"] += 1
                continue
            kind = L.detect(fn, raw[:200].decode("utf-8", "replace"))
            if not kind:
                stats["skip:not_code"] += 1
                continue
            if not L.wanted(kind[0], langs):
                stats["skip:language"] += 1
                continue
            text, why = clean_source(raw, fn, max_kb)
            if text is None:
                stats["skip:" + why] += 1
                continue
            stats["redacted"] += why
            yield rp, kind[0], kind[1], text


def find_license(root):
    for fn in sorted(os.listdir(root)) if os.path.isdir(root) else []:
        if LICENSE_NAME.match(fn):
            try:
                head = open(os.path.join(root, fn), encoding="utf-8", errors="replace").read(400)
            except OSError:
                continue
            return guess_license(head) or fn
    return None


def guess_license(text):
    t = text.lower()
    for key, words in (("mit", "permission is hereby granted, free of charge"), ("apache-2.0", "apache license"),
                       ("bsd-3-clause", "neither the name"), ("bsd-2-clause", "redistribution and use"),
                       ("unlicense", "this is free and unencumbered software"), ("isc", "permission to use, copy, modify"),
                       ("gpl", "gnu general public license"), ("mpl-2.0", "mozilla public license")):
        if words in t:
            return key
    return None


def local(folders, out, langs, max_kb):
    for folder in folders:
        folder = os.path.abspath(os.path.expanduser(folder.strip().strip('"')))
        if not os.path.isdir(folder):
            say(f"local: {folder} is not a folder, skipped")
            continue
        name = slug(folder)
        dest = os.path.join(out, "local", name)
        say(f"local: reading {folder}")
        stats, by_lang = Counter(), Counter()
        w = Writer(dest, fresh=True)
        dedup = Dedup(None)
        project = os.path.basename(os.path.normpath(folder)) or "project"
        t0 = time.time()
        try:
            for rel, lang, com, text in scan_folder(folder, langs, max_kb, stats):
                if not dedup.new(text):
                    stats["skip:duplicate"] += 1
                    continue
                w.write(make_doc(f"{project}/{rel}", com, text), path=rel, lang=lang)
                stats["files"] += 1
                stats["chars"] += len(text)
                by_lang[lang] += 1
                if stats["files"] % 500 == 0:
                    say(f"  {stats['files']} files…")
        finally:
            w.close()
        info = {"folder": folder, "name": project, "files": stats["files"], "chars": stats["chars"],
                "redacted": stats["redacted"], "langs": dict(by_lang.most_common()),
                "skipped": {k[5:]: v for k, v in stats.items() if k.startswith("skip:")},
                "license": find_license(folder), "updated": time.time()}
        with open(os.path.join(dest, "info.json"), "w") as f:
            json.dump(info, f, indent=1)
        top = ", ".join(f"{k} {v}" for k, v in by_lang.most_common(5))
        say(f"local: {project}: {stats['files']} files ({stats['chars'] / 1e6:.1f}M chars) in {time.time() - t0:.0f}s"
            f" · {top or 'no code found'} · {stats['redacted']} secrets redacted · skipped "
            + ", ".join(f"{k} {v}" for k, v in info["skipped"].items()))


# ---------------------------------------------------------------- GitHub
def gh_session(token):
    import requests

    s = requests.Session()
    s.headers.update({"User-Agent": UA, "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"})
    if token:
        s.headers["Authorization"] = f"Bearer {token}"
    return s


def gh_get(sess, url, tries, params=None, stream=False):
    """GET with retries; waits out GitHub's rate limit (up to 15 minutes at a time)."""
    from data.build_corpus import NetError, retry

    def go():
        r = sess.get(url, params=params, timeout=(30, 300), stream=stream)
        if r.status_code in (403, 429) and (r.headers.get("X-RateLimit-Remaining") == "0" or "rate limit" in r.text[:500].lower()):
            reset = int(r.headers.get("X-RateLimit-Reset", time.time() + 60))
            wait = max(5, min(900, reset - time.time() + 2, int(r.headers.get("Retry-After", 900))))
            say(f"  GitHub rate limit reached; waiting {wait:.0f}s (set a GitHub token for a higher limit)")
            time.sleep(wait)
            raise NetError("rate limited")
        if r.status_code in (408, 500, 502, 503, 504):
            raise NetError(f"HTTP {r.status_code}")
        return r
    return retry(go, f"fetching {url.split('github.com', 1)[-1][:80]}", tries)


def licence_ok(spdx, allowed):
    return bool(spdx) and spdx.lower() in allowed


def search_repos(sess, lang, lic, min_stars, page, tries):
    q = f'language:"{lang}" license:{lic} stars:>={min_stars} fork:false archived:false'
    r = gh_get(sess, f"{API}/search/repositories", tries,
               params={"q": q, "sort": "stars", "order": "desc", "per_page": 50, "page": page})
    if r.status_code == 422:  # past the 1,000 results GitHub search returns
        return None
    r.raise_for_status()
    return r.json().get("items", [])


def repo_info(sess, full, tries):
    r = gh_get(sess, f"{API}/repos/{full}", tries)
    if r.status_code == 404:
        return None
    r.raise_for_status()
    return r.json()


def repo_files(sess, full, ref, tries, langs, max_kb, max_repo_mb, stats):
    """Download one repository's tarball and return (files, licence text). Only the archive itself
    is downloaded (codeload.github.com), not one request per file."""
    from data.build_corpus import NetError, retry

    def go():
        r = sess.get(f"{CODELOAD}/{full}/tar.gz/{ref}", timeout=(30, 300), stream=True)
        if r.status_code in (408, 429, 500, 502, 503, 504):
            raise NetError(f"HTTP {r.status_code}")
        r.raise_for_status()
        out, lic_text, budget = [], None, max_repo_mb * 1024 * 1024
        with tarfile.open(fileobj=r.raw, mode="r|gz") as tf:
            for m in tf:
                if not m.isfile():
                    continue
                parts = m.name.split("/")[1:]  # drop the "repo-sha/" folder
                if not parts:
                    continue
                rel = "/".join(parts)
                if len(parts) == 1 and LICENSE_NAME.match(parts[0]) and m.size < 200_000:
                    lic_text = tf.extractfile(m).read().decode("utf-8", "replace")
                    continue
                if any(skip_dir(p) for p in parts[:-1]):
                    continue
                if skip_file(parts[-1]):
                    stats["skip:secret_file"] += 1
                    continue
                if m.size > max_kb * 1024:
                    stats["skip:too_big"] += 1
                    continue
                kind = L.detect(parts[-1])
                if not kind and "." not in parts[-1] and m.size < 200_000:
                    head = tf.extractfile(m).read()
                    kind = L.detect(parts[-1], head[:200].decode("utf-8", "replace"))
                    raw = head
                else:
                    raw = None
                if not kind or not L.wanted(kind[0], langs):
                    continue
                raw = raw if raw is not None else tf.extractfile(m).read()
                budget -= len(raw)
                if budget < 0:
                    stats["skip:repo_budget"] += 1
                    break
                text, why = clean_source(raw, parts[-1], max_kb)
                if text is None:
                    stats["skip:" + why] += 1
                    continue
                stats["redacted"] += why
                out.append((rel, kind[0], kind[1], text))
        return out, lic_text
    return retry(go, f"downloading {full}", tries)


def github(out, max_repos, explicit, langs, licences, min_stars, max_kb, max_repo_mb, tries, token):
    d = os.path.join(out, "github")
    os.makedirs(os.path.join(d, "licenses"), exist_ok=True)
    st_p = os.path.join(d, "progress.json")
    st = json.load(open(st_p)) if os.path.exists(st_p) else {}
    st.setdefault("done", [])
    st.setdefault("rejected", {})
    st.setdefault("pages", {})
    st.setdefault("shard", 0)
    st.setdefault("shard_bytes", 0)
    st.setdefault("files", 0)
    st.setdefault("chars", 0)
    done = set(st["done"])
    allowed = set(licences)
    sess = gh_session(token)
    w = Writer(d, st["shard"], st["shard_bytes"])
    dedup = Dedup(os.path.join(d, "hashes.list"))
    attrib = open(os.path.join(d, "attribution.jsonl"), "a", encoding="utf-8")
    stats = Counter()

    def save():
        st["done"] = sorted(done)
        st["shard"], st["shard_bytes"] = w.checkpoint()
        attrib.flush()
        from data.build_corpus import save_state

        save_state(st_p, st)

    def take(repo):
        full = repo["full_name"]
        if full in done or full in st["rejected"]:
            return False
        spdx = (repo.get("license") or {}).get("spdx_id")
        if not licence_ok(spdx, allowed):
            st["rejected"][full] = f"licence {spdx or 'none'} is not on the permissive list"
            say(f"github: {full}: skipped, licence {spdx or 'none'} (only {', '.join(sorted(allowed))})")
            return False
        if repo.get("size", 0) > max_repo_mb * 1024 * 4:  # size is in KB, compressed sources ~4x smaller
            st["rejected"][full] = f"too big ({repo['size'] / 1024:.0f} MB)"
            say(f"github: {full}: skipped, too big ({repo['size'] / 1024:.0f} MB)")
            return False
        ref = repo.get("default_branch") or "HEAD"
        rs = Counter()
        files, lic_text = repo_files(sess, full, ref, tries, langs, max_kb, max_repo_mb, rs)
        if not lic_text:
            st["rejected"][full] = "no LICENSE file at the top of the repository"
            say(f"github: {full}: skipped, no LICENSE file")
            return False
        kept = 0
        for rel, lang, com, text in files:
            if not dedup.new(text):
                rs["skip:duplicate"] += 1
                continue
            w.write(make_doc(f"{full}/{rel}", com, text), path=rel, lang=lang, repo=full, license=spdx)
            kept += 1
            st["files"] += 1
            st["chars"] += len(text)
        lic_file = os.path.join(d, "licenses", full.replace("/", "__") + ".license")
        with open(lic_file, "w", encoding="utf-8") as f:
            f.write(lic_text)
        attrib.write(json.dumps({"repo": full, "url": repo.get("html_url") or f"https://github.com/{full}",
                                 "license": spdx, "ref": ref, "stars": repo.get("stargazers_count"),
                                 "files": kept, "license_file": os.path.relpath(lic_file, out).replace(os.sep, "/"),
                                 "fetched": time.time()}) + "\n")
        done.add(full)
        stats.update(rs)
        say(f"github: {full} ({spdx}, ★{repo.get('stargazers_count', '?')}): {kept} files"
            + (f", {rs['redacted']} secrets redacted" if rs["redacted"] else ""))
        save()
        return True

    try:
        for full in explicit:
            full = full.strip().strip("/").removeprefix("https://github.com/").removesuffix(".git")
            if not re.fullmatch(r"[\w.-]+/[\w.-]+", full):
                say(f"github: {full!r} is not owner/name, skipped")
                continue
            if full in done:
                say(f"github: {full}: already downloaded")
                continue
            info = repo_info(sess, full, tries)
            if not info:
                say(f"github: {full}: not found (or private)")
                continue
            take(info)
        target = max_repos  # in total, counting repositories downloaded earlier and the named ones
        if max_repos > len(done):
            want_langs = sorted(langs) if langs else ["python", "javascript", "typescript"]
            lics = [x for x in SEARCHABLE if x in allowed]
            queries = [(lg, lc) for lg in want_langs for lc in lics]
            while len(done) < target:
                progressed = False
                for lg, lc in queries:  # round robin, so every language gets its share
                    if len(done) >= target:
                        break
                    key = f"{lg}|{lc}|{min_stars}"
                    page = st["pages"].get(key, 1)
                    if page < 0:
                        continue
                    items = search_repos(sess, lg, lc, min_stars, page, tries)
                    finished = True
                    for repo in items or []:
                        if len(done) >= target:
                            finished = False  # a bigger total later continues on this same page
                            break
                        progressed |= take(repo)
                    # Advance only once the whole page is handled; repositories already done or refused
                    # are skipped at once when a page is read again (after a stop, or a bigger total).
                    if finished:
                        st["pages"][key] = -1 if not items else page + 1
                    save()
                    progressed |= bool(items)
                if not progressed:
                    say("github: no more repositories match; lower the minimum stars or add languages")
                    break
    finally:
        save()
        w.close()
        dedup.close()
        attrib.close()
        write_attribution(out)
    say(f"github: {len(done)} repositories, {st['files']} files ({st['chars'] / 1e6:.1f}M chars) in total"
        + (f" · skipped " + ", ".join(f"{k[5:]} {v}" for k, v in stats.items() if k.startswith('skip:')) if stats else ""))


def write_attribution(out):
    """data/code/ATTRIBUTION.md: every repository the code came from, with its licence."""
    rows = {}
    p = os.path.join(out, "github", "attribution.jsonl")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                rows[r["repo"]] = r
    hf = os.path.exists(os.path.join(out, "hf", "progress.json"))
    with open(os.path.join(out, "ATTRIBUTION.md"), "w", encoding="utf-8") as f:
        f.write("# Code used to train the copilot model\n\nOnly permissively licensed code. "
                "Each repository's licence text is in github/licenses/.\n\n")
        if rows:
            f.write("| Repository | Licence | Files |\n|---|---|---|\n")
            for r in sorted(rows.values(), key=lambda r: r["repo"].lower()):
                f.write(f"| [{r['repo']}]({r['url']}) | {r['license']} | {r['files']} |\n")
        if hf:
            f.write(f"\nAlso: files from the Hugging Face dataset [{HF_CODE_REPO}](https://huggingface.co/datasets/"
                    f"{HF_CODE_REPO}) whose per-file licence column is permissive.\n")


