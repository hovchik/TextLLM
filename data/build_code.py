def hf_code(out, max_gb, langs, licences, max_kb, mode, tries, cache, keep_parquet):
    from data.build_corpus import hf_parquet

    allowed = set(licences)
    os.makedirs(os.path.join(out, "hf"), exist_ok=True)
    dedup = Dedup(os.path.join(out, "hf", "hashes.list"))

    def make(code, row):
        kind = L.detect(row.get("path") or "")
        if not kind:
            return None
        text, why = clean_source(code.encode("utf-8", "replace"), row.get("path") or "", max_kb)
        if text is None or not dedup.new(text):
            return None
        return make_doc(f"{row.get('repo_name', 'repo')}/{row.get('path', 'file')}", kind[1], text)

    filters = {"license": lambda v: (v or "").lower() in allowed}
    if langs:
        filters["language"] = lambda v: L.norm(v) in langs
    try:
        hf_parquet(os.path.join(out, "hf"), "GitHub code (Hugging Face)", HF_CODE_REPO, [""], max_gb, mode, tries,
                   cache, keep_parquet, column="code", filters=filters, extra=("repo_name", "path"), make=make,
                   cache_name="github-code-clean")
    finally:
        dedup.close()
        write_attribution(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="data/code")
    ap.add_argument("--local", action="append", default=[], help="a project folder on this PC (repeat for more)")
    ap.add_argument("--github-repos", type=int, default=0,
                    help="public GitHub repositories to have in total, found by search (0 = none)")
    ap.add_argument("--github-repo", action="append", default=[], help="download exactly this owner/name (repeat)")
    ap.add_argument("--min-stars", type=int, default=50, help="GitHub search: only repositories with this many stars")
    ap.add_argument("--max-repo-mb", type=float, default=40, help="skip repositories with more source than this")
    ap.add_argument("--hf-gb", type=float, default=0, help=f"GB of code from {HF_CODE_REPO} (0 = none)")
    ap.add_argument("--hf-mode", choices=["stream", "download"], default="stream")
    ap.add_argument("--cache", default="data/cache")
    ap.add_argument("--keep-parquet", action="store_true")
    ap.add_argument("--langs", default="", help="languages to keep, e.g. python,javascript,c++ (empty = all code)")
    ap.add_argument("--licenses", default=",".join(PERMISSIVE),
                    help="permissive licences to accept (SPDX ids); anything else is refused")
    ap.add_argument("--max-file-kb", type=int, default=256, help="skip larger files (usually data or generated)")
    ap.add_argument("--retries", type=int, default=30)
    a = ap.parse_args()
    langs = L.parse_langs(a.langs)
    lics = [x.strip().lower() for x in a.licenses.split(",") if x.strip()]
    bad = [x for x in lics if x not in PERMISSIVE]
    if bad:
        raise SystemExit(f"not a permissive licence: {', '.join(bad)}. Allowed: {', '.join(PERMISSIVE)}")
    if not (a.local or a.github_repos or a.github_repo or a.hf_gb):
        raise SystemExit("nothing to do: give --local FOLDER, --github-repos N, --github-repo owner/name or --hf-gb G")
    os.makedirs(a.out, exist_ok=True)
    try:
        if a.local:
            local(a.local, a.out, langs, a.max_file_kb)
        if a.github_repos > 0 or a.github_repo:
            github(a.out, a.github_repos, a.github_repo, langs, lics,
                   a.min_stars, a.max_file_kb, a.max_repo_mb, a.retries, os.environ.get("GITHUB_TOKEN", ""))
        if a.hf_gb > 0:
            hf_code(a.out, a.hf_gb, langs, lics, a.max_file_kb, a.hf_mode, a.retries, a.cache, a.keep_parquet)
    except KeyboardInterrupt:
        sys.exit("\nStopped. Run the same command again to continue where it left off.")


if __name__ == "__main__":
    main()
